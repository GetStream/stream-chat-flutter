/// Maps a generated [api.SyncResponse] to the events it carries.
extension SyncResponseMapper on api.SyncResponse {
  /// Converts this response into its events, in the order they arrived.
  List<ChatEvent> toModel() => [for (final event in events) event.toModel()];
}

// An event of a type the SDK has no class for, such as a custom event.
UnknownEvent _unknownFromJson(String type, Map<String, Object?> json) => UnknownEvent(
  type: type,
  rawData: json,
  createdAt: _createdAtFromJson(json['created_at']),
  custom: _read<Map<String, Object?>>(json, 'custom') ?? const {},
  isLocal: false,
);

T? _read<T>(Map<String, Object?> json, String key) => switch (json[key]) {
  final T value => value,
  _ => null,
};

// When an event the SDK has no class for happened, or null when it names no
// time the SDK can read.
DateTime? _createdAtFromJson(Object? json) {
  if (json == null) return null;
  try {
    return const StreamDateTimeConverter().fromJson(json);
  } on FormatException {
    return null;
  }
}
